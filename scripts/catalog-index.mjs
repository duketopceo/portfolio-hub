// Regenerates src/data/catalog/index.ts: one static import per catalog JSON.
// A static index (not a directory read) keeps the data in the standalone build.
// Usage: node scripts/catalog-index.mjs   (npm run catalog:index)
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = fileURLToPath(new URL("../src/data/catalog", import.meta.url));
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".json") && !f.startsWith("_"))
  .sort();
const ident = (i) => `entry${i}`;

const out = [
  "// GENERATED by scripts/catalog-index.mjs. Do not edit; run `npm run catalog:index`.",
  ...files.map((f, i) => `import ${ident(i)} from "./${f}";`),
  "",
  "/** Raw catalog entries; `src/data/projects.ts` validates them with the zod schema. */",
  "export const catalogEntries: readonly unknown[] = [",
  ...files.map((_, i) => `  ${ident(i)},`),
  "];",
  "",
].join("\n");

writeFileSync(join(dir, "index.ts"), out);
console.log(`catalog index: ${files.length} entries`);
