/**
 * Builds the ranking snapshot from catalog entries and stored activity inputs.
 * Import-free so both scripts/rank-projects.mjs (Node's native type stripping)
 * and the vitest staleness check load it; the scoring functions are injected.
 */

export interface SnapshotDeps {
  extendedScore: (
    input: {
      private: boolean;
      hasRepo: boolean;
      liveUrl: boolean;
      demoUrl: boolean;
      embeddable: boolean;
      isLive: boolean;
      stars: number;
      highlights: number;
      techStack: number;
      hasArchitecture: boolean;
      descriptionLength: number;
      isPlatformOrApp: boolean;
      lastActivity: string | null;
      now: number;
    },
    activity: { commits: number; hasRelease: boolean }
  ) => number;
  getPrimaryDeployment: (slug: string) => { url: string; online: boolean } | undefined;
}

export interface ActivityInputs {
  stars: number;
  commits: number;
  lastPush: string | null;
  hasRelease: boolean;
}

export interface CatalogEntryLike {
  slug: string;
  curated: {
    displayName: string;
    private: boolean;
    siteOnly?: boolean;
    liveUrl?: string;
    demoUrl?: string;
    embeddable?: boolean;
    highlights?: unknown[];
    techStack?: unknown[];
    architecture?: string;
    description?: string;
    type: string;
  };
}

export const EMPTY_INPUTS: ActivityInputs = { stars: 0, commits: 0, lastPush: null, hasRelease: false };

/**
 * The snapshot is committed to a public repository, so a private project's
 * activity is stored coarsely: commits rounded down to the hundred, last push
 * to its month, no star count. Idempotent, so a check agrees with a refresh.
 */
export function coarsen(input: ActivityInputs): ActivityInputs {
  return {
    stars: 0,
    commits: Math.floor(input.commits / 100) * 100,
    lastPush: input.lastPush ? `${input.lastPush.slice(0, 7)}-01T00:00:00Z` : null,
    hasRelease: input.hasRelease,
  };
}

/** Builds the score input from a catalog entry (deployment overlay included). */
function scoreEntry(deps: SnapshotDeps, entry: CatalogEntryLike, input: ActivityInputs, now: number): number {
  const c = entry.curated;
  const dep = deps.getPrimaryDeployment(entry.slug);
  const liveUrl = dep ? dep.url : c.liveUrl;
  const demoUrl = c.demoUrl ?? (dep ? dep.url : undefined);
  const offline = dep ? !dep.online : false;
  const isLive = !!(liveUrl || demoUrl) && !offline;
  return deps.extendedScore(
    {
      private: c.private,
      hasRepo: !c.siteOnly,
      liveUrl: !!liveUrl,
      demoUrl: !!demoUrl,
      embeddable: !!c.embeddable,
      isLive,
      stars: input.stars,
      highlights: c.highlights?.length ?? 0,
      techStack: c.techStack?.length ?? 0,
      hasArchitecture: !!c.architecture && c.architecture.trim().length > 0,
      descriptionLength: (c.description ?? "").trim().length,
      isPlatformOrApp: c.type === "platform" || c.type === "app",
      lastActivity: input.lastPush,
      now,
    },
    { commits: input.commits, hasRelease: input.hasRelease }
  );
}

export function buildSnapshot(
  deps: SnapshotDeps,
  entries: readonly CatalogEntryLike[],
  inputs: Record<string, ActivityInputs>,
  asOf: string
) {
  const now = Date.parse(`${asOf}T00:00:00Z`);
  const rows = entries.map((e) => {
    const raw = inputs[e.slug] ?? EMPTY_INPUTS;
    const input = e.curated.private ? coarsen(raw) : raw;
    return { slug: e.slug, name: e.curated.displayName, input, score: scoreEntry(deps, e, input, now) };
  });
  rows.sort((a, b) => b.score - a.score || a.name.localeCompare(b.name));
  return {
    asOf,
    scoreVersion: 1,
    note: "Generated by scripts/rank-projects.mjs. Pages read this file, never live stars or the clock. Refresh deliberately: node scripts/rank-projects.mjs --refresh",
    entries: rows.map((r) => ({ slug: r.slug, score: r.score, inputs: r.input })),
  };
}
